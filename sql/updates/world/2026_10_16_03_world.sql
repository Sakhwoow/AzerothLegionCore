-- Тёмная Гавань: после сдачи "Вторжения" (14321) у игрока пропадали все НПС деревни (Гвен
-- Армстед, Креннан, Годфри, жители) - фаза 181 обрывалась ровно в момент сдачи.
--
-- Фаза 181 (спелл 68481, "деревня до нападения") по spell_area действовала от сдачи 14375 до
-- СДАЧИ 14321 (quest_end=14321, запрещающий статус 64). А следующий квест "Убей или будь убит"
-- (14336) выдаёт та самая Гвен Армстед (34571), которая живёт именно в фазе 181, и переключение
-- 181 -> 182 ("нападение") в C++-скрипте Гвен делается при ПРИНЯТИИ 14336: OnQuestAccept
-- снимает 68481 и вешает 68482. Строки spell_area опережали скрипт на один шаг: фаза менялась
-- в момент сдачи 14321, Гвен исчезала до того, как успевала выдать 14336, а ближайший выдающий
-- этот квест Принц Лиам (36140, фаза 182) стоит в ~90 ярдах у ворот.
--
-- Теперь 181 держится, пока 14336 не принят (запрещающие статусы 14336: 74 = принят/выполнен/сдан):
-- Гвен остаётся на месте, выдаёт 14336, и скрипт переключает фазу на 182 как задумано.
-- Строки для остальных подзон Тёмной Гавани (4792, 4793, 4806-4808, 4818, 5720) и зоны Гилнеас
-- (4714) сдвигаются так же, чтобы фаза не расходилась между подзонами.
UPDATE `spell_area` SET `quest_end`=14336, `quest_end_status`=74 WHERE `spell`=68481 AND `quest_start`=14375 AND `quest_end`=14321;
