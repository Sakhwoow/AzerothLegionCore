-- Тёмная Гавань и окрестности (зона 4714): игрок с квестовой фазой не видит объекты в "нормальной"
-- фазе 0 - бочки с чёрным порохом (кв. "Одному не справиться", 14348), почтовый ящик, кузню,
-- наковальню, котёл и объекты ферм. Квестовые спеллы фаз (68481, 68482, 67789 и т.д.) в этом
-- ядре заменяют нормальную фазу (169), а БД собрана из сниффов, где нормальная фаза у игрока
-- сохранялась, и такие объекты записаны с PhaseId=0.
--
-- Вне города в фазе 0 лежит 71 объект (GO) и ни одного существа, поэтому возврат нормальной
-- фазы не покажет лишних НПС. Используем штатный спелл 172329 "Set Self to Normal Phase"
-- (аура PHASE 169): строки spell_area для него уже есть в БД для других зон (4298, 4809, 5332,
-- 7025, 7705, 9171). Ставим одну строку на всю зону Гилнеас (4714, подзоны Тёмная Гавань,
-- фермы Аллена и Хаммонда, Берег Тёмной Дымки). Город (4755) не затрагивается.
DELETE FROM `spell_area` WHERE `spell`=172329 AND `area`=4714;
