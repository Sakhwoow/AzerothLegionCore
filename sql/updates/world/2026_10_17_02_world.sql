-- Гилнеас (карта 654): сведение окон квестовых фаз 179-184 и 190 в одну непротиворечивую цепочку
-- Last Stand -> Тёмная Гавань -> усадьба Седогривов -> осада города.
--
-- Окно фазы = пересечение строк spell_area, условий каста в conditions (SourceTypeOrReferenceId=17) и
-- скриптов. Условия каста блокируют только ПРИМЕНЕНИЕ ауры (в том числе автокаст), снимает ауру только
-- spell_area (AUTOREMOVE / CheckLocation) или скрипт. Правки ниже получены сверкой всех трёх источников
-- по каждому шагу цепочки (модель на живой БД: до правок нарушено 10 из 19 стадий, после - нет).
--
-- 1-2) Фаза 182 (нападение Отрёкшихся, спелл 68482) начиналась на 14375, за три квеста до "Вторжения"
--      (14321): две "вечные" строки (4786/14336 с маской 75 включает любой статус, 4714/14347 без конца).
--      Узкая строка 14321 снимала ауру при принятии 14321 и она мигала. Строки удалены, остаются окна
--      [14321 сдан .. 14396 принят). Условие каста сдвинуто с "не сдан 14386" на "не сдан 14396": иначе
--      потерянную на 14386-14396 фазу 182 нельзя вернуть, а Годфри (36290, выдаёт 14396) стоит только в ней.
--      УДАЛЯТЬ строки и менять условие нужно ТОЛЬКО вместе: условие без удаления даёт возврат 182 после
--      принятия 14396 и ломает переход на 183 (скрипт Годфри снимает 181/182 и вешает 183).
DELETE FROM `spell_area` WHERE `spell`=68482 AND `area`=4786 AND `quest_start`=14336 AND `aura_spell`=0;
DELETE FROM `spell_area` WHERE `spell`=68482 AND `area`=4714 AND `quest_start`=14347 AND `aura_spell`=0;
UPDATE `conditions` SET `ConditionValue1`=14396, `Comment`='(AND) spell if NOT rewarded quest 14396 (As the Land Shatters): attack phase 182 lasts until then' WHERE `SourceTypeOrReferenceId`=17 AND `SourceGroup`=0 AND `SourceEntry`=68482 AND `ElseGroup`=1 AND `ConditionTypeOrReference`=8 AND `ConditionValue1`=14386 AND `NegativeCondition`=1;

-- 3) Фаза 183 (после "Как земля раскололась", спелл 68483) не кончалась никогда: строки 14386 и 4786/14397 без
--    конца, поэтому Тёмная Гавань навсегда оставалась с "призраками" 183. Окно: [14386 сдан .. 24438 сдан)
--    ("Исход": Генн 36743 стоит только в 183 и выдаёт 24438), как у существующей строки усадьбы 4817.
UPDATE `spell_area` SET `quest_end`=24438, `quest_end_status`=64 WHERE `spell`=68483 AND `area`=4714 AND `quest_start`=14386 AND `aura_spell`=0;
DELETE FROM `spell_area` WHERE `spell`=68483 AND `area`=4786 AND `quest_start`=14397 AND `aura_spell`=0;

-- 4) Фаза 184 (спелл 69077) в усадьбе Седогривов: строк для Гилнеаса не было вообще (только Дренор, области
--    7041 и 7043), поэтому CheckLocation снимал ауру при первой же смене подзоны, и Королеву Мию (36606, сдаёт
--    14465 и выдаёт 14466, стоит только в фазе 184) игрок не видел. Окно: [14465 принят .. 14466 принят),
--    на всю зону 4714 (область усадьбы 4817 и 6545 - её подзоны), статусы принят/выполнен/сдан = 74.
DELETE FROM `spell_area` WHERE `spell`=69077 AND `area`=4714 AND `quest_start`=14465;
INSERT INTO `spell_area` (`spell`, `area`, `quest_start`, `quest_end`, `aura_spell`, `teamId`, `racemask`, `gender`, `flags`, `quest_start_status`, `quest_end_status`) VALUES
(69077, 4714, 14465, 14466, 0, -1, 0, 2, 3, 74, 74);

-- 5) Фаза 179 (сцена прибытия, спелл 67789) залипала навсегда: строки 4714/4755 без конца. Конец - сдача 14375,
--    как у условия каста; иначе Генн, Креннан и Годфри (копии фазы 179) остаются видимыми рядом с их копиями
--    в фазе 181 (двойники в 20 ярдах).
UPDATE `spell_area` SET `quest_end`=14375, `quest_end_status`=64 WHERE `spell`=67789 AND `area` IN (4714, 4755) AND `quest_start`=14222 AND `aura_spell`=0;

-- 6) Фаза 190 (город после "Битвы за Гилнеас-Сити", спелл 70696): рабочих строк не было (строка area=0
--    в автокасте не участвует - карта ищет только по ненулевым областям; её и скрипт Lost Isles с кастом
--    68481 трогать нельзя). Генн 38539 (принимает 24903) и Принц Лиам 38614 стоят только в фазе 190, условие
--    каста "сдан 24904" уже есть. Строка 4758 (Двор Седогрива) срабатывает сразу при сдаче 24904 (там стоят
--    НПС, SendQuestUpdate смотрит точную подзону), строка 4755 покрывает остальные подзоны города.
DELETE FROM `spell_area` WHERE `spell`=70696 AND `area` IN (4755, 4758) AND `quest_start`=24904;
INSERT INTO `spell_area` (`spell`, `area`, `quest_start`, `quest_end`, `aura_spell`, `teamId`, `racemask`, `gender`, `flags`, `quest_start_status`, `quest_end_status`) VALUES
(70696, 4755, 24904, 0, 0, -1, 0, 2, 3, 64, 11),
(70696, 4758, 24904, 0, 0, -1, 0, 2, 3, 64, 11);
