-- Квест "Слушая наше дыхание" (Gasping for Breath, 14395, спасти 4 утопающих стражей) был невыполним:
-- утопающих (36440) было видно, но кликнуть по ним нельзя.
--
-- Механика (zone_duskhaven.cpp, npc_drowning_watchman_36440 и spell_rescue_drowning_watchman_68735):
-- игрок кликает по стражу, заклинание 68735 делает игрока транспортом (аура SET_VEHICLE_ID, транспорт 520),
-- страж садится на игрока, игрок плывёт к берегу к Принцу Лиаму (36451), скрипт засчитывает спасение.
--
-- 1) У шаблона 36440 не было флага UNIT_NPC_FLAG_SPELLCLICK (0x1000000 = 16777216): клиент не показывает курсор
--    клика и не отправляет клик вообще. У транспортных НПС (пушка повстанцев, лошади, катапульты) этот флаг
--    ставит код Vehicle при создании, а у стража VehicleId = 0, поэтому флаг должен быть в шаблоне. Строка в
--    npc_spellclick_spells при этом была, но без флага она не используется.
-- 2) В строке npc_spellclick_spells (36440, 68735) стоял cast_flags = 0: тогда заклинание накладывает сам страж
--    на самого себя (Unit::HandleSpellClick: caster = clicker только при флаге 1). Скрипт и SpellScript
--    ждут ИГРОКА-заклинателя (caster->ToPlayer(), GetCaster()->GetVehicleKit()), поэтому ничего бы не сработало
--    и после включения флага. cast_flags = 1 (заклинатель - кликнувший, цель - страж) стоит у 3399 строк таблицы,
--    это общепринятое значение для клика игроком.
-- Откат: npcflag = 0 у 36440, cast_flags = 0 у строки (36440, 68735).
-- Бэкап строк: /root/legion_backup_20261017_phasepack/creature_template_36440.sql и npc_spellclick_36440.sql.
--
-- Не тронуто (кликабельные НПС карты 654 без флага и без транспорта, поведение неясно): Chance 36459 (спеллклик
-- 68743), Glaive Thrower 38150, Hippogryph 43747 - разобрать, когда игрок дойдёт до их квестов.
UPDATE `creature_template` SET `npcflag`=`npcflag` | 16777216 WHERE `entry`=36440 AND (`npcflag` & 16777216)=0;
UPDATE `npc_spellclick_spells` SET `cast_flags`=1 WHERE `npc_entry`=36440 AND `spell_id`=68735 AND `cast_flags`=0;
