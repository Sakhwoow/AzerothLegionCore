-- Квест "В поместье Седогрива" (To Greymane Manor, 14465): у него нет ни одной цели в quest_objectives и не стоял флаг
-- SpecialFlags = 2 (QUEST_SPECIAL_FLAGS_EXPLORATION_OR_EVENT), поэтому Player::AddQuestAndCheckCompletion переводил квест
-- в "выполнен" в момент взятия (в character_queststatus у персонажа 1763 это status = 1, explored = 0). Скрипты ворот на
-- дороге к поместью (go_gate_196399, go_gate_196401) открывали ворота только игроку с квестом "в процессе", поэтому
-- ворота оставались закрытыми, а сам квест мог "закрыться" без поездки.
-- SpecialFlags = 2: квест остаётся "в процессе", пока скрипт коня (vehicle_swift_mountain_horse_36741) не вызовет
-- AreaExploredOrEventHappens после того, как конь проехал вторые ворота у поместья.
-- Скрипты ворот при этом открывают ворота и тем, кто уже взял квест и получил его как "выполнен" (status = 1):
-- у таких персонажей квест остаётся выполненным, конь им нужен только чтобы доехать до Мии.
-- Откат: SpecialFlags = 0 у 14465.
UPDATE `quest_template_addon` SET `SpecialFlags` = `SpecialFlags` | 2 WHERE `ID` = 14465 AND (`SpecialFlags` & 2) = 0;
